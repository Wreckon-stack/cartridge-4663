export const GLYPH_W = 5
export const GLYPH_H = 7

/**
 * Render text into a list of {x, y} pixel coordinates on a 5x7 grid per glyph.
 * Unknown characters fall back to a space rather than throwing, so a caption
 * can never break the build.
 */
export function textPixels(text, { letterSpacing = 1 } = {}) {
  const pixels = []
  let cursor = 0
  for (const char of text.toUpperCase()) {
    const glyph = G[char] ?? G[' ']
    for (let row = 0; row < GLYPH_H; row += 1) {
      const line = glyph[row] ?? ''
      for (let col = 0; col < GLYPH_W; col += 1) {
        if (line[col] === '#') pixels.push({ x: cursor + col, y: row })
      }
    }
    cursor += GLYPH_W + letterSpacing
  }
  return { pixels, width: Math.max(0, cursor - letterSpacing), height: GLYPH_H }
}

/** Measured advance width of `text` in grid cells. */
export function textWidth(text, { letterSpacing = 1 } = {}) {
  const count = [...text].length
  if (count === 0) return 0
  return count * (GLYPH_W + letterSpacing) - letterSpacing
}

/**
 * Emit an SVG <g> of rects for `text`.
 * `scale` is the size of one pixel in user units.
 */
export function textSvg(text, { x = 0, y = 0, scale = 4, fill = '#fff', letterSpacing = 1, id } = {}) {
  const { pixels } = textPixels(text, { letterSpacing })
  const rects = pixels
    .map((p) => `<rect x="${x + p.x * scale}" y="${y + p.y * scale}" width="${scale}" height="${scale}"/>`)
    .join('')
  return `<g fill="${fill}"${id ? ` id="${id}"` : ''}>${rects}</g>`
}
